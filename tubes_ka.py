plt.title('KNN: Validation Accuracy vs. n_neighbors (Euclidean Metric)')
plt.xlabel('Number of Neighbors (n_neighbors)')
plt.ylabel('Mean Test Accuracy')
plt.xticks(uniform_weights_euclidean['param_n_neighbors'].unique())
plt.grid(True, linestyle='--', alpha=0.7)
plt.legend()
plt.show()

